// PRModel represents a pull request in the database (GORM model)
type PRModel struct {
	ID              uint            `gorm:"primaryKey;autoIncrement"`
	RepoOwner       string          `gorm:"size:255;not null;uniqueIndex:idx_prs_unique"`
	RepoName        string          `gorm:"size:255;not null;uniqueIndex:idx_prs_unique"`
	PRNumber        int             `gorm:"not null;uniqueIndex:idx_prs_unique"`
	Title           string          `gorm:"type:text"`
	Author          string          `gorm:"size:255;index"`
	LastCommitSHA   string          `gorm:"size:40;not null"`
	Status          string          `gorm:"size:20;default:pending;index"`
	ReviewPath      string          `gorm:"column:review_path;type:text;index"`
	LastReviewedAt  *time.Time      `gorm:"index"`
	GeneratingSince *time.Time      `gorm:"index"`
	CreatedAt       *time.Time      `gorm:"index"`
	Draft           bool            `gorm:"default:false"`
	ApprovalCount   int             `gorm:"default:0"`
	MyReviewStatus  string          `gorm:"size:20"` // "APPROVED", "CHANGES_REQUESTED", "COMMENTED", or ""
	CIState         string          `gorm:"size:20;default:unknown"`
	CIFailedChecks  JSONStringArray `gorm:"type:text"`
	// GitHub PR state: "open", "closed", or "merged". Only diverges from
	// "open" on rows retained past close (manual claims) — everything else
	// is deleted at close by cleanup.
	PRState string `gorm:"column:pr_state;size:16;default:open"`
	// The latest review was generated by an agent that fell back to a
	// different model than requested. Written by MarkPRCompleted.
	ModelFallback bool `gorm:"column:model_fallback;default:false"`
	// ReviewRunID is indexed for telemetry correlation; ReviewRunJSON stores
	// the full additive payload.ReviewRunInfo without coupling db to payload.
	ReviewRunID   string `gorm:"column:review_run_id;size:36;index"`
	ReviewRunJSON string `gorm:"column:review_run_json;type:text"`
	// ProjectionRunID fences mutable PR status/result writes across overlapping
	// service instances. It records the most recent run allowed to project and
	// intentionally remains set after that run becomes terminal.
	ProjectionRunID string `gorm:"column:projection_run_id;size:36"`
	// Review importance counts (populated after review generation)
	CriticalCount int `gorm:"default:0"`
	MediumCount   int `gorm:"default:0"`
	LowCount      int `gorm:"default:0"`
	// Overall review verdict parsed from the SUMMARY entry:
	// "request_changes", "approve_suggestions", "approve", or "" (unknown).
	// Written alongside the counts by MarkPRCompleted.
	ReviewVerdict string `gorm:"column:review_verdict;size:32"`
	// User notes (single-user mode)
	Notes string `gorm:"size:15"`
	// Poll economy: last seen updated_at from GitHub search API
	GitHubUpdatedAt *time.Time `gorm:"column:github_updated_at"`
	// Populated when Status=="error"; surfaced to the UI.
	ErrorMessage string `gorm:"column:error_message;type:text"`
	// How many times the auto-retry path has reset this PR back to pending
	// after an error. Capped by ResetErrorPRs so deterministic failures
	// (auth misconfig, model outage) don't burn quota indefinitely. Legacy
	// manual admission and successful completion reset it; run-aware automatic
	// admission intentionally preserves it so retries cannot re-arm themselves.
	ErrorRetryCount int `gorm:"column:error_retry_count;default:0"`
}

// TableName specifies the table name for PRModel
func (PRModel) TableName() string {
	return "prs"
}

