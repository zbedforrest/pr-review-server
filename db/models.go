// UserPRViewModel represents the relationship between users and PRs (GORM model)
type UserPRViewModel struct {
	ID           uint            `gorm:"primaryKey;autoIncrement"`
	UserID       uint            `gorm:"uniqueIndex:idx_user_pr_unique;not null"`
	User         UserModel       `gorm:"foreignKey:UserID;constraint:OnDelete:CASCADE"`
	PRID         uint            `gorm:"column:pr_id;uniqueIndex:idx_user_pr_unique;not null"`
	PR           PRModel         `gorm:"foreignKey:PRID;constraint:OnDelete:CASCADE"`
	IsAuthor     bool            `gorm:"default:false"`
	IsReviewer   bool            `gorm:"default:false"`
	ViaTeams     JSONStringArray `gorm:"type:text"` // JSON array of team names
	ReviewStatus string          `gorm:"size:20"`   // "APPROVED", "CHANGES_REQUESTED", "COMMENTED", or ""
	Notes        string          `gorm:"size:15"`
	Hidden       bool            `gorm:"default:false"`
	// User-initiated "move to Hidden section" toggle. Distinct from Hidden,
	// which is a poller-managed soft delete that the poll cycle resets on
	// every upsert; UserHidden is only ever written by the user and must
	// never appear in a poller DoUpdates set.
	UserHidden bool `gorm:"column:user_hidden;default:false"`
	// The user requested a review for this PR by hand (generate-review).
	// Same write discipline as UserHidden: only the generate-review handler
	// writes it, never any poller DoUpdates or prune set. While true (and
	// not Hidden) it also exempts a closed PR from cleanup deletion.
	ViaManual bool `gorm:"column:via_manual;default:false"`
}

